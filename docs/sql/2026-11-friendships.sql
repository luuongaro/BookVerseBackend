CREATE TABLE IF NOT EXISTS friendships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_external UUID NOT NULL UNIQUE,
    user_low_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_high_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    requester_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT friendships_ordered_pair CHECK (user_low_id < user_high_id),
    CONSTRAINT friendships_requester_member CHECK (requester_id IN (user_low_id, user_high_id)),
    CONSTRAINT friendships_unique_pair UNIQUE (user_low_id, user_high_id)
);
CREATE INDEX IF NOT EXISTS friendships_high_status_idx ON friendships (user_high_id, status);
